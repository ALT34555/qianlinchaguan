    "layout(location=0) in vec2 aPos;\n"
    "layout(location=1) in vec2 aUV;\n"
    "uniform vec2 uScreen;\n"
    "out vec2 vUV;\n"
    "void main() {\n"
    "    vec2 ndc = vec2((aPos.x / uScreen.x) * 2.0 - 1.0, 1.0 - (aPos.y / uScreen.y) * 2.0);\n"
    "    gl_Position = vec4(ndc, 0.0, 1.0);\n"
    "    vUV = aUV;\n"
    "}\n";

/* 舆图全功能着色器（3投影 + 11图层  */
static const char *ATLAS_FS_SRC =
    "#version 330 core\n"
    "in vec2 vUV;\n"
    "uniform sampler2D uTex0;\n"
    "uniform sampler2D uTex1;\n"
    "uniform sampler2D uSatTex;\n"
    "uniform sampler2D uTileTex;\n"
    "uniform sampler2D uTileMeta;\n"
    "uniform sampler2D uTileWater;\n"
    "uniform float uRiverMix;\n"
    "uniform float uIcePhase;\n"
    "uniform int   uIceValid;\n"
    "uniform sampler2D uRainTex;\n"
    "uniform int   uDetailLevel;\n"
    "uniform float uTileSamples;\n"
    "uniform vec2  uVpSize;\n"
    "uniform vec2  uCamW;\n"
    "uniform vec2  uTileOrigin;\n"
    "uniform vec2  uTileFraction;\n"
    "uniform vec2  uTilePixelStep;\n"
    "uniform float uCirc; uniform int uFlat,uFlatSolarType; uniform float uFlatSun,uFlatEclipse;\n"
    "uniform vec4 uFlatRect; uniform float uFlatCells;\n"
    "uniform float uZoomScale;\n"
    "uniform int   uViewMode;\n"
    "uniform int   uSatMode;\n"
    "uniform vec2  uGlobeRot;\n"
    "uniform float uGlobeRadius;\n"
    "uniform float uSunLon;\n"
    "uniform float uSunLat;\n"
    "uniform int uAstro,uLunarEclipse,uEclipseKind; uniform vec3 uSolarPosition,uLunarPosition; uniform sampler2D uEclipseChart;\n"
    "uniform float uSimTime;\n"
    "uniform int   uContourDensity;\n"
    "uniform float uContourStep;\n"
    "uniform int   uQuickFilter;\n"
    "uniform int uLayerId;\n"
    "uniform float uLayerOpacity;\n"
    "out vec4 FragColor;\n"
    "\n"
    "vec3 hsv_heat(float t) {\n"
    "    t = clamp(t, 0.0, 1.0);\n"
    "    return mix(vec3(0.16, 0.42, 0.86), mix(vec3(0.28, 0.78, 0.42), vec3(0.92, 0.28, 0.18), smoothstep(0.45, 1.0, t)), smoothstep(0.0, 0.65, t));\n"
    "}\n"
    "\n"
    "/* 舆图冰层：逐常数复刻 ice_model.c */\n"
    "float atlas_ice_primitive(float m, float a, float lo, float hi) {\n"
    "    return (m * (hi - lo) - a * (cos(hi) - cos(lo))) / 0.0174532925;\n"
    "}\n"
    "\n"
    "float atlas_ice_cover(float h) {\n"
    "    return smoothstep(0.004, 0.020, h);\n"
    "}\n"
    "\n"
    "/* 传 phase 0..4，返回 H（米）；qOut 质量 */\n"
    "float atlas_ice_thickness(float annual, float lat, float phase, float depth,\n"
    "                          float u, float b, uint kind, out float qOut) {\n"
    "    /* 0.5 为舆图尺度概括噪声 */\n"
    "    const float NOS = 0.5;\n"
    "    const float OMEGA = 0.0174532925;\n"
    "    const float TAU = 6.283185307;\n"
    "    const float PI = 3.141592654;\n"
    "    qOut = 1.0;\n"
    "    float d = max(depth, 0.0);\n"
    "    if (d <= 0.02 || kind == 0u || kind == 4u) return 0.0;\n"
    "    /* 热滞后：深水与近岸更慢 */\n"
    "    float lag = clamp(0.6 + 0.65 * min(d, 16.0) - 0.4 * b, 0.25, 12.0);\n"
    "    float wlag = OMEGA * lag;\n"
    "    float samp = 16.0 * sin(lat);\n"
    "    float amp = abs(samp) / sqrt(1.0 + wlag * wlag);\n"
    "    float shift = -atan(wlag) + (samp < 0.0 ? PI : 0.0);\n"
    "    float point = (kind == 1u) ? -1.8 : 0.0;\n"
    "    float mean = annual - point + 2.0 * u;\n"
    "    float k2 = 0.00075 * (1.0 - 0.55 * u) * (0.9 + 0.2 * NOS);\n"
    "    if (kind == 1u) k2 *= 0.7;\n"
    "    float km = 0.012 * (1.0 + 0.8 * b + 0.6 * u);\n"
    "    float debt = 1.5 + 1.8 * min(d, 12.0) + 5.0 * u;\n"
    "    float cap = max(0.0, min(d, kind == 3u ? 0.70 : 1.20));\n"
    "    if (mean - amp >= 0.0) return 0.0;\n"
    "    if (mean + amp <= 0.0) return cap;\n"
    "    if (amp < 1e-10) return (mean < 0.0) ? cap : 0.0;\n"
    "    float phi = OMEGA * (90.0 * phase) + shift;\n"
    "    /* 冷期起点/终点为气温过零点 */\n"
    "    float ang = asin(clamp(-mean / amp, -1.0, 1.0));\n"
    "    float c0 = PI - ang;\n"
    "    float c1 = TAU + ang;\n"
    "    float cold = max(0.0, -atlas_ice_primitive(mean, amp, c0, c1));\n"
    "    float warm = max(0.0, atlas_ice_primitive(mean, amp, c1, c0 + TAU));\n"
    "    float capC = k2 * max(0.0, cold - debt);\n"
    "    float decH = km * warm;\n"
    "    /* 周期稳定解：冷期起始残冰 h0 */\n"
    "    float h0 = cap;\n"
    "    if (decH > 1e-12) {\n"
    "        h0 = clamp((capC - decH * decH) / (2.0 * decH), 0.0, max(0.0, cap - decH));\n"
    "    }\n"
    "    float peak = min(cap, sqrt(h0 * h0 + capC));\n"
    "    float ratio = (peak > 1e-12) ? h0 / peak : 0.0;\n"
    "    float decay = exp(-warm / 18.0);\n"
    "    float den = 1.0 - ratio * decay;\n"
    "    float peakQ = (den > 1e-12) ? (1.0 - ratio) / den : 1.0;\n"
    "    float oldQ = max(0.08, peakQ * decay);\n"
    "    peakQ = ratio * oldQ + 1.0 - ratio;\n"
    "    float vv = c0 + mod(phi - c0, TAU);\n"
    "    float h = 0.0;\n"
    "    float q = 1.0;\n"
    "    if (vv <= c1) {\n"
    "        float coldv = max(0.0, -atlas_ice_primitive(mean, amp, c0, vv));\n"
    "        h = min(cap, sqrt(h0 * h0 + k2 * max(0.0, coldv - debt)));\n"
    "        q = (h > 1e-12) ? (h0 * oldQ + max(0.0, h - h0)) / h : 1.0;\n"
    "    } else {\n"
    "        float warmv = max(0.0, atlas_ice_primitive(mean, amp, c1, vv));\n"
    "        h = max(0.0, peak - km * warmv);\n"
    "        q = max(0.08, peakQ * exp(-warmv / 18.0));\n"
    "    }\n"
    "    h = clamp(h, 0.0, max(0.0, d));\n"
    "    qOut = clamp(q, 0.08, 1.0);\n"
    "    return h;\n"
    "}\n"
    "\n"
    "float eclipse(vec3 o,out int kind){\n"
    "    if(uFlat!=0){kind=uFlatSolarType;return uFlatEclipse;}kind=0;vec3 s=uSolarPosition-o,m=uLunarPosition-o;\n"
    "    if(dot(s,o)<=0.0)return 0.0;\n"
    "    float rs=asin(46.5/length(s)),rm=asin(.2724/length(m)),d=atan(length(cross(normalize(s),normalize(m))),dot(normalize(s),normalize(m)));\n"
    "    if(d>=rs+rm)return 0.0;\n"
    "    kind=1;if(d<=abs(rs-rm)){kind=rm>=rs?2:3;return min(1.0,rm*rm/(rs*rs));}\n"
    "    float a=acos(clamp((d*d+rs*rs-rm*rm)/(2.0*d*rs),-1.0,1.0));\n"
    "    float b=acos(clamp((d*d+rm*rm-rs*rs)/(2.0*d*rm),-1.0,1.0));\n"
    "    return (rs*rs*a+rm*rm*b-.5*sqrt(max(0.0,(-d+rs+rm)*(d+rs-rm)*(d-rs+rm)*(d+rs+rm))))/(3.14159265359*rs*rs);\n"
    "}\n"
    "void main() {\n"
    "    vec2 p = (vUV - 0.5) * uVpSize;\n"
    "    vec2 mapUV = vec2(0.0);\n"
    "    float globeShade = 1.0;\n"
    "    if (uViewMode == 0) {\n"
    "        float rad = uGlobeRadius;\n"
    "        vec2 sp = p / rad;\n"
    "        float r2 = dot(sp, sp);\n"
    "        if (r2 > 1.0) {\n"
    "            float halo = exp(-(sqrt(r2) - 1.0) * 14.0);\n"
    "            if (uLayerId != -1) discard;\n"
    "            FragColor = vec4(mix(vec3(0.07, 0.09, 0.11), vec3(0.28, 0.48, 0.68), halo * 0.55), 1.0);\n"
    "            return;\n"
    "        }\n"
    "        float z = sqrt(1.0 - r2);\n"
    "        vec3 n = vec3(sp.x, -sp.y, z);\n"
    "        float clat = cos(uGlobeRot.y), slat = sin(uGlobeRot.y);\n"
    "        vec3 n1 = vec3(n.x, n.y * clat + n.z * slat, -n.y * slat + n.z * clat);\n"
    "        float clon = cos(uGlobeRot.x), slon = sin(uGlobeRot.x);\n"
    "        vec3 wpos = vec3(n1.x * clon + n1.z * slon, n1.y, -n1.x * slon + n1.z * clon);\n"
    "        float lon = atan(wpos.x, wpos.z);\n"
    "        float lat = asin(clamp(wpos.y, -1.0, 1.0));\n"
    "        mapUV = vec2(lon / 6.2831853 + 0.5, 0.5 - lat / 3.1415926);\n"
    "        globeShade = 0.72 + 0.28 * z;\n"
    "    } else {\n"
    "        float wx = uCamW.x + p.x / uZoomScale;\n"
    "        float wz = uCamW.y + p.y / uZoomScale;\n"
    "        float halfZ = uCirc * (uFlat!=0?.5:.25);\n"
    "        if (uViewMode == 2) {\n"
    "            float mercY = clamp(wz / halfZ, -0.98, 0.98) * 1.45;\n"
    "            float lat = 2.0 * atan(exp(mercY)) - 1.5707963;\n"
    "            mapUV.y = 0.5 + lat / 3.1415926;\n"
    "        } else {\n"
    "            if (uFlat==0 && abs(wz) > halfZ) {\n"
    "                if (uLayerId != -1) discard;\n"
    "                FragColor = vec4(0.11, 0.13, 0.12, 1.0);\n"
    "                return;\n"
    "            }\n"
    "            mapUV.y = (wz + halfZ) / (halfZ * 2.0);\n"
    "        }\n"
    "        mapUV.x = uFlat!=0?wx/uCirc+.5:fract(wx / uCirc + 0.5);\n"
    "    }\n"
    "\n"
    "    bool currentPlane=all(greaterThanEqual(mapUV,vec2(0))) && all(lessThanEqual(mapUV,vec2(1)));\n"
    "    vec2 macroUV=mapUV;\n"
    "    if(uFlat!=0){\n"
    "        vec2 size=vec2(textureSize(uSatTex,0));\n"
    "        macroUV=(mapUV*uFlatCells-uFlatRect.xy)/uFlatRect.zw;\n"
    "        bool outside=any(lessThan(macroUV,vec2(0))) || any(greaterThanEqual(macroUV,vec2(1)));\n"
    "        if(outside || texelFetch(uSatTex,ivec2(floor(macroUV*size)),0).a<.5){\n"
    "            if(uLayerId!=-1)discard;FragColor=vec4(.11,.13,.12,1);return;\n"
    "        }\n"
    "    }\n"
    "    vec4 t0 = texture(uTex0, macroUV);\n"
    "    vec4 t1 = texture(uTex1, macroUV);\n"
    "    vec4 ts = texture(uSatTex, macroUV);\n"
    "\n"
    "    float op = uLayerOpacity;\n"
    "    float alon=(mapUV.x-.5)*6.28318530718,alat=(.5-mapUV.y)*3.14159265359;\n"
    "    vec3 observer=vec3(cos(alat)*cos(alon),sin(alat),cos(alat)*sin(alon));\n"
    "    if(uLayerId==-3){\n"
    "        vec4 chart=texture(uEclipseChart,mapUV);vec3 tint=vec3(.25,.6,1.0);float a=0.0;\n"
    "        if(uEclipseKind==1){tint=mix(tint,vec3(.65,.35,1.0),chart.g);tint=mix(tint,vec3(1.0,.6,.15),chart.b);a=chart.a*.23;}\n"
    "        if(uEclipseKind==2){tint=mix(vec3(.5,.65,.8),vec3(.8,.35,.2),chart.g);tint=mix(tint,vec3(.7,.15,.15),chart.b);a=chart.a*.23;}\n"
    "        int kind;float cover=eclipse(observer,kind);\n"
    "        if(kind>0){tint=kind==2?vec3(.65,.35,1.0):kind==3?vec3(1.0,.6,.15):vec3(.25,.6,1.0);a=.4+cover*.3;}\n"
    "        if(uLunarEclipse>0&&(uFlat!=0||dot(uLunarPosition-observer,observer)>0.0)){tint=uLunarEclipse==1?vec3(.5,.65,.8):uLunarEclipse==2?vec3(.8,.35,.2):vec3(.7,.16,.12);a=.38;}\n"
    "        FragColor=vec4(tint,a);return;\n"
    "    }\n"
    "    if (uLayerId == 3) {\n"
    "        float lon = (mapUV.x - 0.5) * 6.2831853;\n"
    "        float lat = (0.5 - mapUV.y) * 3.1415926;\n"
    "        float cosZen = sin(lat) * sin(uSunLat) + cos(lat) * cos(uSunLat) * cos(lon - uSunLon);\n"
    "        if(uAstro!=0)cosZen=dot(normalize(uSolarPosition-observer),observer);\n"
    "        if(uFlat!=0)cosZen=uFlatSun;\n"
    "        float night = 1.0 - smoothstep(-0.14, 0.08, cosZen);\n"
    "        if(uAstro!=0){int kind;float cover=eclipse(observer,kind);night=max(night,cover*.97); }\n"
    "        FragColor = vec4(mix(vec3(1.0), vec3(0.24, 0.28, 0.42), night * op), 1.0);\n"
    "        return;\n"
    "    }\n"
    "    if (uLayerId == 4) {\n"
    "        vec4 rn = texture(uRainTex, mapUV);\n"
    "        FragColor = vec4(rn.rgb * globeShade, rn.a * op * 0.70);\n"
    "        return;\n"
    "    }\n"
    "    if (uLayerId == 2) {\n"
    "        if (abs(mapUV.x - 0.5) >= 0.0018 && abs(mapUV.y - 0.5) >= 0.0022) discard;\n"
    "        FragColor = vec4(vec3(0.88, 0.72, 0.32) * globeShade, op * 0.85);\n"
    "        return;\n"
    "    }\n"
    "    if (uLayerId == 7) {\n"
    "        float temp = t1.r * 90.0 - 45.0;\n"
    "        FragColor = vec4(hsv_heat((temp + 30.0) / 65.0) * globeShade, op * 0.78);\n"
    "        return;\n"
    "    }\n"
    "    if (uLayerId == -2) {\n"
    "        int maskBits = int(t1.a * 255.0 + 0.5);\n"
    "        if (uQuickFilter <= 0 || (maskBits & (1 << (uQuickFilter - 1))) == 0) discard;\n"
    "        FragColor = vec4(vec3(0.902, 0.224, 0.275) * globeShade, 0.72);\n"
    "        return;\n"
    "    }\n"
    "\n"
    "    float elev = t0.a;\n"
    "    float temp = t1.r * 90.0 - 45.0;\n"
    "    vec3 col = (uSatMode == 1) ? ts.rgb : t0.rgb;\n"
    "    float sourceCoverage = 0.0;\n"
    "    float iceWet = (elev <= 0.0 || t1.b > 0.5) ? 1.0 : 0.0;\n"
    "    /* 分级细节瓦片：命中槽位则替换地表色与高程 */\n"
    "    if (uDetailLevel > 0 && uSatMode == 0 && (uFlat==0 || currentPlane)) {\n"
    "        float n = exp2(float(uDetailLevel));\n"
    "        float spanM = uCirc / n;\n"
    "        float ftx = mapUV.x * n;\n"
    "        float fty = mapUV.y * n * (uFlat!=0?1.0:0.5);\n"
    "        float fxi = floor(ftx);\n"
    "        float fyi = clamp(floor(fty), 0.0, n * (uFlat!=0?1.0:0.5) - 1.0);\n"
    "        vec2 tileFraction = vec2(ftx - fxi, fty - fyi);\n"
    "        if (uViewMode != 0 && uDetailLevel >= 16) {\n"
    "            vec2 local = uTileFraction + p * uTilePixelStep;\n"
    "            fxi = mod(uTileOrigin.x + floor(local.x), n);\n"
    "            fyi = clamp(uTileOrigin.y + floor(local.y), 0.0, n * (uFlat!=0?1.0:0.5) - 1.0);\n"
    "            tileFraction = fract(local);\n"
    "        }\n"
    "        int sx = int(fxi) & 15;\n"
    "        int sy = int(fyi) & 15;\n"
    "        int sl = sx + sy * 16;\n"
    "        vec4 m0 = texelFetch(uTileMeta, ivec2(sl * 2, 0), 0);\n"
    "        vec4 m1 = texelFetch(uTileMeta, ivec2(sl * 2 + 1, 0), 0);\n"
    "        if (abs(m0.x - fxi) < 0.75 && abs(m0.y - fyi) < 0.75 &&\n"
    "            abs(m0.z - float(uDetailLevel)) < 0.75 && m1.y > 0.004) {\n"
    "            float pitch = uTileSamples + 2.0;\n"
    "            vec2 f = tileFraction * uTileSamples + 1.0;\n"
    "            vec2 tuv = (vec2(float(sx), float(sy)) * pitch + f) / (pitch * 16.0);\n"
    "            vec4 dt = texture(uTileTex, tuv);\n"
    "            vec4 waterInfo = texture(uTileWater, tuv);\n"
    "            float coverage = smoothstep(0.02, 0.02+max(fwidth(waterInfo.r),0.0001), waterInfo.r);\n"
    "            sourceCoverage = smoothstep(0.02,0.02+max(fwidth(waterInfo.a),0.0001),waterInfo.a) * uRiverMix;\n"
    "            iceWet = mix(iceWet, coverage, m1.y);\n"
    "            if (spanM / uTileSamples <= 8.0) {\n"
    "                float deep = 1.0-exp(-max(0.0,waterInfo.r)/(waterInfo.b<0.0?26.0:4.0));\n"
    "                vec3 water = mix(vec3(0.42,0.69,0.70),vec3(0.10,0.28,0.40),deep);\n"
    "                float tint = dt.a*2.0-1.0;\n"
    "                float shallow = 1.0-smoothstep(0.0,16.0,max(0.0,waterInfo.r));\n"
    "                water = mix(water,vec3(0.55,0.60,0.43),max(-tint,0.0)*shallow);\n"
    "                water = mix(water,vec3(0.51,0.76,0.70),max(tint,0.0)*shallow);\n"
    "                dt.rgb = mix(dt.rgb,water,coverage);\n"
    "            }\n"
    "            temp = mix(temp, waterInfo.g * 90.0 - 45.0, m1.y);\n"
    "            col = mix(col, dt.rgb, m1.y);\n"
    "            elev = mix(elev, waterInfo.b, m1.y);\n"
    "        }\n"
    "    }\n"
    "\n"
    "    if (uLayerId == 11) {\n"
    "        FragColor = vec4(vec3(0.20,0.44,0.55)*globeShade,sourceCoverage*op);\n"
    "        return;\n"
    "    }\n"
    "    if (uLayerId == 5) {\n"
    "        float gradient = length(vec2(dFdx(elev), dFdy(elev)));\n"
    "        float unit = max(uContourStep, 0.02);\n"
    "        float shade = 1.0;\n"
    "        if (uContourDensity > 0 && elev > 0.0 && iceWet < 0.5 &&\n"
    "            (gradient <= 0.0 || unit / gradient >= 6.0)) {\n"
    "            float band = fract(elev / unit);\n"
    "            shade = 0.84 + 0.24 * min(1.0, (1.0 - band) * 2.6);\n"
    "            if (gradient > 0.0) {\n"
    "                float distance = min(band, 1.0 - band) * unit / gradient;\n"
    "                shade *= 1.0 - (1.0-smoothstep(0.0,1.4,distance)) * 0.34;\n"
    "            }\n"
    "        }\n"
    "        FragColor = vec4(vec3(mix(1.0, clamp(shade, 0.0, 1.0), op)), 1.0);\n"
    "        return;\n"
    "    }\n"
    "\n"
    "    if (uLayerId == -1) {\n"
    "        FragColor = vec4(col * globeShade, 1.0);\n"
    "        return;\n"
    "    }\n"
    "    vec3 layerColor = vec3(0.0);\n"
    "    float alpha = 0.0;\n"
    "    if (uLayerId == 10 && elev < 0.0) {\n"
    "        float dp = clamp(-elev / 3200.0, 0.0, 1.0);\n"
    "        layerColor = mix(vec3(0.24, 0.64, 0.78), vec3(0.04, 0.12, 0.28), dp);\n"
    "        alpha = op * 0.85;\n"
    "    } else if (uLayerId == 8 && elev >= 0.0) {\n"
    "        float eh = clamp(elev / 2400.0, 0.0, 1.0);\n"
    "        layerColor = mix(vec3(0.28, 0.66, 0.34), mix(vec3(0.84, 0.74, 0.38), vec3(0.92, 0.90, 0.94), smoothstep(0.45, 1.0, eh)), smoothstep(0.0, 0.55, eh));\n"
    "        alpha = op * 0.85;\n"
    "    } else if (uLayerId == 6 && elev >= 0.0) {\n"
    "        layerColor = (temp > 23.0) ? vec3(0.88, 0.36, 0.22) : ((temp > 15.0) ? vec3(0.90, 0.68, 0.24) : ((temp > 4.0) ? vec3(0.34, 0.72, 0.42) : ((temp > -5.0) ? vec3(0.28, 0.58, 0.78) : vec3(0.76, 0.86, 0.95))));\n"
    "        alpha = op * 0.70;\n"
    "    } else if (uLayerId == 9 && iceWet > 0.5) {\n"
    "        if (uIceValid == 0 || uIcePhase < 0.0) discard;\n"
    "        /* 远景河湖概括 depth=2m、u=0、b=0 */\n"
    "        /* 舆图不显示 2m 交互孔洞 */\n"
    "        /* temp 命中细节瓦片时已是逐像素年温 */\n"
    "        float ilat = (0.5 - mapUV.y) * 3.1415926;\n"
    "        /* 海水区 elev<0 用 SEA */\n"
    "        uint ikind = (elev < 0.0) ? 1u : 2u;\n"
    "        float iq = 1.0;\n"
    "        float ih = atlas_ice_thickness(temp, ilat, uIcePhase, 2.0, 0.0, 0.0, ikind, iq);\n"
    "        float icov = atlas_ice_cover(ih);\n"
    "        if (icov < 0.5) discard;\n"
    "        /* 冰色与 3D 冰顶同向：新→成长→厚 */\n"
    "        float grow = smoothstep(0.02, 0.25, ih);\n"
    "        vec3 ic = mix(vec3(0.220, 0.380, 0.435), vec3(0.604, 0.776, 0.839), smoothstep(0.0, 0.55, grow));\n"
    "        ic = mix(ic, vec3(0.784, 0.874, 0.902), smoothstep(0.55, 1.0, grow));\n"
    "        ic = mix(ic, vec3(0.455, 0.561, 0.596), (1.0 - smoothstep(0.45, 0.95, iq)) * 0.72);\n"
    "        layerColor = ic;\n"
    "        alpha = op * 0.85 * icov;\n"
    "    }\n"
    "    if (alpha <= 0.0) discard;\n"
    "    FragColor = vec4(layerColor * globeShade, alpha);\n"
    "}\n";

