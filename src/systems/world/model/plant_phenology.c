static int season_offset(float temperature, int season, uint32_t rank) {
    static const float slope[4] = { -.6f, -.3f, .6f, .6f };
    float limit = season == 1 ? 3.0f : 6.0f;
    int mu = (int)roundf(qlcg_clampf((temperature - 15.0f) * slope[season], -limit, limit));
    const uint32_t *cdf = SEASON_CDF[mu + 6];
    int lo = 0, hi = 30;
    while (lo < hi) {
        int mid = (lo + hi) / 2;
        if (rank >= cdf[mid]) lo = mid + 1;
        else hi = mid;
    }
    return lo - 15;
}

int qlcg_plant_visual_season(const QlcgClimateSeason *cs,
                             float temperature, uint32_t identity) {
    if (!cs) return 1;
    int season = cs->season;
    if (season < 0 || season > 3) season = 1;
    if (cs->seasonless) return season;

    float since = cs->since_days;
    float until = cs->until_days;
    if (since < 0.0f) since = 0.0f;
    if (until < 0.0f) until = 0.0f;
    /* 短季压缩错峰窗口，避免前后条件重叠 */
    float window = 15.0f;
    float half = (since + until) * 0.5f;
    if (half < window) window = half;
    if (window < 1.0f) return season;
    if (since >= window && until > window) return season;

    uint32_t rank = qlcg_hash_u32(identity ^ 0x7068656eu) >> 8;
    if (since < window && since < season_offset(temperature, season, rank))
        return (season + 3) % 4;
    int next = (season + 1) % 4;
    if (until <= window && -until >= season_offset(temperature, next, rank))
        return next;
    return season;
}
