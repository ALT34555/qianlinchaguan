    "uniform int uUnderwater;\n"
    "uniform vec3 uWaterFog;\n";

static const char *GB_LIB_B =
    "vec3 gb_sky_mood(vec3 paper){return uPaintSky;}\n"
    "float gb_patch_fade(vec2 posXZ){return 0.0;}\n"
    "vec3 gb_snow_color(){return uPaintSnow;}\n"
    "vec3 gb_atmosphere(vec3 intrinsicCol, float snowMask, float edgeScale, vec3 wPos, vec3 eyePos, vec2 px, out float airOut){\n"
    "  vec3 paper = gb_paper(px);\n"
    "  vec3 skyPaper = gb_sky_mood(paper);\n"
    "  float dist = length(wPos - eyePos);\n"
    "  float fogNear=uPaintFog.x,fogFar=uPaintFog.y;\n"
    "  float air = clamp((dist - fogNear) / max(fogFar - fogNear, 1.0), 0.0, 1.0);\n"
    "  air = pow(air, 0.88);\n"
    "  float hRel = max(wPos.y - (uBaseY - 2.0), 0.0);\n"
    "  float mistBand = exp(-hRel * 0.095) * smoothstep(58.0, 132.0, dist) * 0.8 * 0.26;\n"
    "  float edgeFade = gb_patch_fade(wPos.xz) * edgeScale;\n"
    "  float totalAir = clamp(max(air * 0.8, mistBand), 0.0, 0.94);\n"
    "  airOut = max(totalAir, edgeFade);\n"
    "  vec3 col = intrinsicCol;\n"
    "  if (uPalette == 2) col = mix(gb_warm_ink(col), col, snowMask);\n"
    "  if (uPalette == 0){\n"
    "    float nearVivid = mix(1.30, 0.72, totalAir) * clamp(uPigment, 0.35, 1.32);\n"
    "    col = gb_sat(col, mix(nearVivid, 0.85, snowMask));\n"
    "    float azurShift = smoothstep(0.18, 0.72, totalAir) * (1.0 - snowMask * 0.85) * 0.24;\n"
    "    col = mix(col, mix(skyPaper, vec3(0.32, 0.56, 0.62), 0.68), azurShift);\n"
    "    if (uPigment < 0.75) col = mix(paper, col, uPigment / 0.75);\n"
    "  } else if (uPalette == 1){\n"
    "    float nearVivid = mix(1.22, 0.68, totalAir) * clamp(uPigment, 0.35, 1.30);\n"
    "    col = gb_sat(col, mix(nearVivid, 0.85, snowMask));\n"
    "    if (uPigment < 0.75) col = mix(paper, col, uPigment / 0.75);\n"
    "  } else {\n"
    "    col = mix(skyPaper, col, clamp(uPigment, 0.35, 1.12));\n"
    "  }\n"
    "  vec3 snowFar=uPaintSnowFar;\n"
    "  vec3 target = mix(skyPaper, snowFar, snowMask);\n"
    "  float distMix = mix(totalAir, totalAir * 0.42, snowMask);\n"
    "  vec3 res = mix(col, target, distMix);\n"
    "  if (uDust > 0.02){\n"
    "    float dustF = clamp(smoothstep(14.0, 96.0, dist) * uDust * 0.78, 0.0, 0.85);\n"
    "    vec3 dustC = (uPalette == 2) ? vec3(0.73, 0.69, 0.62) : vec3(0.84, 0.74, 0.53);\n"
    "    res = mix(res, dustC, dustF);\n"
    "  }\n"
    "  res = mix(res, skyPaper, edgeFade);\n"
    "  if(uUnderwater!=0) res=mix(res,uWaterFog,clamp((dist-1.0)/35.0,0.0,1.0));\n"
    "  return clamp(res, 0.0, 1.0);\n"
    "}\n";

