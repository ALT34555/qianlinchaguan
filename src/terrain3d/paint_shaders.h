    "  float c = log(max(ink_linear(texelFetch(uDepth, clamp(ip + ivec2(0, 1), ivec2(0), hi), 0).r), 0.15));\n"
    "  float d = log(max(ink_linear(texelFetch(uDepth, clamp(ip + ivec2(1, 1), ivec2(0), hi), 0).r), 0.15));\n"
    "  return mix(mix(a, b, f.x), mix(c, d, f.x), f.y);\n"
    "}\n"
    "vec3 ink_position(vec2 uv,float depth){\n"
    "  float z=exp(depth);\n"
    "  return vec3((uv*2.0-1.0)*uProjection*z,-z);\n"
    "}\n"
    "uniform vec2 uEdgeRange;\n"
    "float raw_min(vec2 uv, ivec2 hi){\n"
    "  ivec2 p=ivec2(floor(uv/uTexel-0.5));\n"
    "  float a=texelFetch(uDepth,clamp(p,ivec2(0),hi),0).r;\n"
    "  float b=texelFetch(uDepth,clamp(p+ivec2(1,0),ivec2(0),hi),0).r;\n"
    "  float c=texelFetch(uDepth,clamp(p+ivec2(0,1),ivec2(0),hi),0).r;\n"
    "  float d=texelFetch(uDepth,clamp(p+ivec2(1),ivec2(0),hi),0).r;\n"
    "  return min(min(a,b),min(c,d));\n"
    "}\n"
    "float distance_factor(vec2 uv){return length(vec3((uv*2.0-1.0)*uProjection,1));}\n"
    "void main(){\n"
    "  vec4 center = texture(uTex, vUv);\n"
    "  vec2 stepUV = uTexel * max(0.55, uLineWidth);\n"
    "  vec2 material=texture(uTerrain,vUv).rg;\n"
    "  float terrain=step(0.25,material.r);\n"
    "  vec2 boldStep=uTexel*max(1.5,uLineWidth*2.75);\n"
    "  vec2 dirs[8]=vec2[8](vec2(1,0),vec2(0.707107,0.707107),vec2(0,1),vec2(-0.707107,0.707107),\n"
    "    vec2(-1,0),vec2(-0.707107,-0.707107),vec2(0,-1),vec2(0.707107,-0.707107));\n"
    "  if(terrain>0.5){\n"
    "    if(material.r<0.9){frag=vec4(center.rgb,1);return;}\n"
    "    float ridge=0.0,border=1.0;\n"
    "    for(int i=0;i<8;i++){\n"
    "      vec2 uv=vUv+dirs[i]*boldStep*2.5;vec2 tag=texture(uTerrain,uv).rg;float m=tag.r;\n"
    "      border=min(border,tag.r+tag.g);\n"
    "      if(m<0.999)ridge=max(ridge,(1.0-m)*step(0.9999995,texture(uDepth,uv).r));\n"
    "    }\n"
    "    if(ridge>0.0){frag=vec4(mix(center.rgb,uInkDeep,clamp(ridge*uStrength*0.78,0.0,0.90)*0.92),1);return;}\n"
    "    if(border>=0.999){frag=vec4(center.rgb,1);return;}\n"
    "  }else if(material.g>0.001){\n"
    "    float centerDepth=texture(uDepth,vUv).r;\n"
    "    float z=ink_linear(centerDepth);\n"
    "    float edgeDistance=z*distance_factor(vUv);\n"
    "    if(edgeDistance>128.0){frag=vec4(center.rgb,1);return;}\n"
    "    vec2 plantStep=boldStep*mix(1.0,0.5,clamp((edgeDistance-16.0)/48.0,0.0,1.0));\n"
    "    float maxRaw=centerDepth;\n"
    "    for(int i=0;i<8;i++){\n"
    "      maxRaw=max(maxRaw,texture(uDepth,vUv+dirs[i]*plantStep).r);\n"
    "    }\n"
    "    float outline=smoothstep(0.018,0.16,(ink_linear(maxRaw)-z)/max(z,0.15));\n"
    "    float snow=1.0-smoothstep(0.84,0.95,min(center.r,min(center.g,center.b)))*0.72;\n"
    "    float fade=mix(1.0,0.25,clamp((edgeDistance-64.0)/64.0,0.0,1.0));\n"
    "    float density=clamp(outline*material.g*uStrength*0.78*snow,0.0,0.90)*0.92*fade;\n"
    "    frag=vec4(mix(center.rgb,uInkDeep,density),1);return;\n"
    "  }\n"
    "  vec4 left = texture(uTex, vUv - vec2(stepUV.x, 0.0));\n"
    "  vec4 right = texture(uTex, vUv + vec2(stepUV.x, 0.0));\n"
    "  vec4 down = texture(uTex, vUv - vec2(0.0, stepUV.y));\n"
    "  vec4 up = texture(uTex, vUv + vec2(0.0, stepUV.y));\n"
    "  float gain = clamp(1.0 - center.a, 0.0, 1.0);\n"
    "  vec4 neighborPlant=vec4(texture(uTerrain,vUv-vec2(stepUV.x,0)).g,texture(uTerrain,vUv+vec2(stepUV.x,0)).g,\n"
    "    texture(uTerrain,vUv-vec2(0,stepUV.y)).g,texture(uTerrain,vUv+vec2(0,stepUV.y)).g);\n"
    "  vec4 neighborWeights=(1.0-vec4(left.a,right.a,down.a,up.a))*(1.0-step(vec4(0.001),neighborPlant));\n"
    "  float neighborGain=max(max(neighborWeights.x,neighborWeights.y),max(neighborWeights.z,neighborWeights.w));\n"
    "  if(max(gain,neighborGain)<0.001){frag=vec4(center.rgb,1);return;}\n"
    "  float centerDepth=texture(uDepth,vUv).r;\n"
    "  float edgeDistance=ink_linear(centerDepth)*distance_factor(vUv);\n"
    "  ivec2 hi = textureSize(uDepth, 0) - 1;\n"
    "  if(edgeDistance>=uEdgeRange.x){\n"
    "    float nearestRaw=1.0;\n"
    "    for(int y=-1;y<=1;y++)for(int x=-1;x<=1;x++)\n"
    "      nearestRaw=min(nearestRaw,raw_min(vUv+vec2(x,y)*stepUV,hi));\n"
    "    vec2 closest=max(abs(vUv*2.0-1.0)-2.0*(stepUV+uTexel),vec2(0));\n"
    "    edgeDistance=ink_linear(nearestRaw)*length(vec3(closest*uProjection,1));\n"
    "    if(edgeDistance>=uEdgeRange.y){frag=vec4(center.rgb,1);return;}\n"
    "  }\n"
    "  float edgeFade=1.0-smoothstep(uEdgeRange.x,uEdgeRange.y,edgeDistance);\n"
    "  float z = ink_logdepth(vUv, hi);\n"
    "  float zl = ink_logdepth(vUv - vec2(stepUV.x, 0.0), hi);\n"
    "  float zr = ink_logdepth(vUv + vec2(stepUV.x, 0.0), hi);\n"
    "  float zd = ink_logdepth(vUv - vec2(0.0, stepUV.y), hi);\n"
    "  float zu = ink_logdepth(vUv + vec2(0.0, stepUV.y), hi);\n"
    "  float zld = ink_logdepth(vUv - stepUV, hi);\n"
    "  float zru = ink_logdepth(vUv + stepUV, hi);\n"
    "  float zlu = ink_logdepth(vUv + vec2(-stepUV.x, stepUV.y), hi);\n"
    "  float zrd = ink_logdepth(vUv + vec2(stepUV.x, -stepUV.y), hi);\n"
    "  float jump = max(max(abs(zl-z), abs(zr-z)), max(abs(zd-z), abs(zu-z)));\n"
    "  float lap = max(abs(zl + zr - 2.0*z), abs(zu + zd - 2.0*z)) * 0.5;\n"
    "  lap = max(lap, max(abs(zld+zru-2.0*z), abs(zlu+zrd-2.0*z)) * 0.31);\n"
    "  vec2 grad = vec2(zr-zl, zu-zd) + vec2(zru+zrd-zlu-zld, zru+zlu-zrd-zld) * 0.35;\n"
    "  float nearest = exp(min(z, min(min(zl,zr), min(zd,zu))));\n"
    "  float far = smoothstep(24.0, 148.0, nearest);\n"
    "  float silhouette = smoothstep(0.018, 0.16, jump);\n"
    "  float structure = smoothstep(0.004 + far*0.005, 0.035 + far*0.025, lap);\n"
    "  float bone = max(silhouette, structure * 0.62) * gain;\n"
    "  float colorLap = max(length(left.rgb + right.rgb - center.rgb * 2.0),\n"
    "                       length(up.rgb + down.rgb - center.rgb * 2.0));\n"
    "  float colorLine = smoothstep(0.12, 0.42, colorLap) * gain * 0.20 * (1.0-far*0.85);\n"
    "  float outside = max(neighborGain - gain, 0.0) * silhouette * 0.14;\n"
    "  float line = max(bone, colorLine);\n"
    "  line=mix(line,silhouette*gain,terrain);\n"

    "  vec3 washed = center.rgb;\n"
    "  vec3 acc = center.rgb;\n"
    "  float total = 1.0;\n"
    "  vec4 colors[4] = vec4[4](left, right, down, up);\n"
    "  float depths[4] = float[4](zl, zr, zd, zu);\n"
    "  for (int i=0; i<4; i++){\n"
    "    float weight = exp(-abs(depths[i]-z)*38.0 - length(colors[i].rgb-center.rgb)*12.0);\n"
    "    weight *= 1.0 - smoothstep(0.05, 0.28, abs(colors[i].a-center.a));\n"
    "    acc += colors[i].rgb * weight;\n"
    "    total += weight;\n"
    "  }\n"
    "  washed = mix(washed, acc/total, uWash * gain * (1.0-silhouette*0.75));\n"
    "  \n"
    "  vec2 tangent = vec2(-grad.y, grad.x) / max(length(grad), 0.0001);\n"
    "  vec3 alongA = texture(uTex, vUv + tangent * uTexel * 0.45).rgb;\n"
    "  vec3 alongB = texture(uTex, vUv - tangent * uTexel * 0.45).rgb;\n"
    "  washed = mix(washed, (alongA+alongB)*0.5, silhouette * 0.20);\n"
    "  float snow = 1.0 - smoothstep(0.84, 0.95, min(washed.r, min(washed.g,washed.b))) * 0.72;\n"
    "  float distanceFade = 1.0 - far * 0.88;\n"
    "  float density = clamp((line * 0.76 + outside) * distanceFade * snow * uStrength, 0.0, 0.86);\n"
    "  vec3 ink = mix(uInk, uInkDeep, bone * (1.0-far) * 0.64);\n"
    "  ink = mix(washed, ink, 0.70 + bone * 0.22);\n"
    "  vec3 result=mix(washed,ink,density);\n"
    "  frag=vec4(mix(center.rgb,result,edgeFade),1.0);\n"
    "}\n";

