static const char *SKY_FS_SRC =
    "#version 330 core\n"
    "in vec2 vNDC;\n"
    "uniform vec3  uCamFwd;\n"
    "uniform vec3  uCamRight;\n"
    "uniform vec3  uCamUp;\n"
    "uniform float uTanHalfFov;\n"
    "uniform float uAspect;\n"
    "uniform vec3  uSunDir;\n"
    "uniform vec3  uHorizon;\n"
    "uniform int uUnderwater;\n"
    "uniform vec3  uZenith;\n"
    "uniform vec3  uGlowColor;\n"
    "uniform vec3  uMoonDir;\n"
    "uniform vec3  uCloudColor;\n"
    "uniform float uGlow;\n"
    "uniform float uStar;\n"
    "uniform int uAstronomy,uLunarPhase; uniform sampler2D uAstralMap; uniform vec3 aEast,aUp,aSouth;\n"
    "uniform float uSunRadius,uMoonRadius,uSolarCover,uShadowRadius,uPenumbraRadius; uniform vec3 uShadowDir;\n"
    "uniform vec3 uOcculter; uniform float uOcculterRadius;\n"
    "uniform float uMoon;\n"
    "uniform float uCloudCov;\n"
    "uniform vec3  uRainCloudColor;\n"
    "uniform float uRainAlpha;\n"
    "uniform float uFlash;\n"
    "uniform float uSimTime;\n"
    "out vec4 FragColor;\n"
    "float sHash(vec3 p) { p = fract(p * 0.1031); p += dot(p, p.yzx + 33.33); return fract((p.x + p.y) * p.z); }\n"
    "float sNoise(vec2 p) {\n"
    "    vec2 i = floor(p), f = fract(p);\n"
    "    vec2 u = f * f * (3.0 - 2.0 * f);\n"
    "    return mix(mix(sHash(vec3(i, 0.0)), sHash(vec3(i + vec2(1.0, 0.0), 0.0)), u.x),\n"
    "               mix(sHash(vec3(i + vec2(0.0, 1.0), 0.0)), sHash(vec3(i + vec2(1.0, 1.0), 0.0)), u.x), u.y);\n"
    "}\n"
    "void main() {\n"
    "    if (uUnderwater != 0) { FragColor = vec4(uHorizon, 1.0); return; }\n"
    "    vec3 dir = normalize(uCamFwd + vNDC.x * uAspect * uTanHalfFov * uCamRight + vNDC.y * uTanHalfFov * uCamUp);\n"
    "    vec3 col = mix(uHorizon, uZenith, pow(clamp(dir.y, 0.0, 1.0), 1.35));\n"
    "    vec3 atmosphere=col;\n"
    "    if(uAstronomy!=0 && dir.y>0.0){vec3 p=dir.x*aEast+dir.y*aUp+dir.z*aSouth;\n"
    "        vec2 uv=vec2(atan(p.y,p.x)/6.28318530718,asin(clamp(p.z,-1.0,1.0))/3.14159265359+.5);\n"
    "        col+=texture(uAstralMap,uv).rgb*uStar*smoothstep(0.0,.18,dir.y); }\n"
    "    float sun = max(dot(dir, uSunDir), 0.0);\n"
    "    vec3 haze=uGlowColor*uGlow*pow(sun,4.0);col+=haze;atmosphere+=haze;\n"
    "    float sr=uLunarPhase!=0?uSunRadius:acos(.9975),mr=uLunarPhase!=0?uMoonRadius:acos(.9985);\n"
    "    float sunAngle=atan(length(cross(dir,uSunDir)),dot(dir,uSunDir));\n"
    "    if(sunAngle<sr && (uLunarPhase==0 || dir.y>0.0)) col=mix(col,uGlowColor*2.2+vec3(.35),.9);\n"
    "    if(uLunarPhase!=0 && uSolarCover>.995 && dir.y>0.0){float r=sunAngle/sr;\n"
    "        col+=vec3(.25,.28,.32)*exp(-max(0.0,r-1.0)*2.5)*smoothstep(1.0,1.08,r);}\n"
    "    if(uMoon>.001 && (uLunarPhase==0 || dir.y>0.0)) {\n"
    "        float moon=max(dot(dir,uMoonDir),0.0);\n"
    "        if(dot(dir,uMoonDir)>0.0 && length(cross(dir,uMoonDir))<sin(mr)){\n"
    "            if(uLunarPhase!=0){vec3 tangent=(dir-uMoonDir*moon)/sin(mr);\n"
    "                vec3 normal=tangent-uMoonDir*sqrt(max(0.0,1.0-dot(tangent,tangent)));\n"
    "                float lit=smoothstep(-.03,.03,dot(normal,uSunDir));\n"
    "                float sd=atan(length(cross(dir,uShadowDir)),dot(dir,uShadowDir));\n"
    "                float um=1.0-smoothstep(uShadowRadius*.96,uShadowRadius*1.04+.000001,sd);\n"
    "                float pen=1.0-smoothstep(uShadowRadius,uPenumbraRadius+.000001,sd);\n"
    "                vec3 surface=mix(vec3(.92,.95,1.0)*(1.0-pen*.45),vec3(.18,.035,.012),um);\n"
    "                col=mix(atmosphere,surface,lit*uMoon*.92);\n"
    "            }else col=mix(col,vec3(.92,.95,1.0),.92);\n"
    "        }else if(uLunarPhase==0) col+=vec3(.55,.62,.78)*pow(moon,90.0)*.35*uMoon;\n"
    "    }\n"
    "    if(uLunarPhase!=0 && uOcculterRadius>0.0 && dir.y>0.0 && dot(dir,uOcculter)>0.0 && length(cross(dir,uOcculter))<sin(uOcculterRadius)) col=atmosphere;\n"
    "    if (uAstronomy == 0 && uStar > 0.02 && dir.y > 0.0) {\n"
    "        vec3 sp = dir * 120.0;\n"
    "        float h = sHash(floor(sp));\n"
    "        float core = smoothstep(0.34, 0.0, length(fract(sp) - 0.5));\n"
    "        col += vec3(0.85, 0.90, 1.0) * step(0.994, h) * core * uStar\n"
    "             * smoothstep(0.0, 0.18, dir.y);\n"
    "    }\n"
    "    /* 雨云内壳：降水灰蓝雨幕（base Sky） */\n"
    "    if (uRainAlpha > 0.001) {\n"
    "        float rc = 0.5 + 0.25 * sin(dir.x * 12.0 + dir.z * 7.0)\n"
    "                       + 0.25 * cos(dir.z * 15.0 - dir.y * 8.0);\n"
    "        float cov = smoothstep(-0.12, 0.06, dir.y);\n"
    "        col = mix(col, uRainCloudColor * (0.9 + 0.1 * rc),\n"
    "                  uRainAlpha * cov * (0.88 + 0.12 * rc));\n"
    "    }\n"
    "    if (dir.y > 0.02 && uCloudCov > 0.02) {\n"
    "        vec2 cuv = dir.xz / (dir.y + 0.18) * 1.8 + vec2(uSimTime * 0.012, uSimTime * 0.007);\n"
    "        float n = sNoise(cuv * 1.6) * 0.6 + sNoise(cuv * 3.7 + 11.0) * 0.4;\n"
    "        float cl = smoothstep(0.62 - uCloudCov * 0.22, 0.95, n);\n"
    "        vec3 ccol = uCloudColor * (0.85 + 0.3 * n);\n"
    "        col = mix(col, ccol, cl * clamp(uCloudCov * 0.55, 0.0, 0.92) * smoothstep(0.02, 0.25, dir.y));\n"
    "    }\n"
    "    col += vec3(0.90, 0.94, 1.0) * uFlash * 0.18;\n"
    "    FragColor = vec4(col, 1.0);\n"
    "}\n";

