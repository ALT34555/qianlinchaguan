static const char *TERR_FS_SRC =
    "#version 330 core\n"
    "in vec3 vPos;\n"
    "in vec3 vNorm;\n"
    "in vec3 vCol;\n"
    "uniform vec3  uSunDir;\n"
    "uniform vec3  uCamPos;\n"
    "uniform vec3  uFogCol;\n"
    "uniform vec2  uFogRange;\n"
    "uniform int uUnderwater;\n"
    "uniform vec3  uBrushPos;\n"
    "uniform float uBrushRad;\n"
    "uniform float uLightScale;\n"
    "uniform vec3  uTint;\n"
    "uniform float uGroundDetail;\n"
    "uniform int uCliffMaterial;\n"
    "uniform sampler2D uGroundTex0;\n"
    "uniform sampler2D uGroundTex1;\n"
    "uniform float uGroundMix;\n"
    "uniform vec2  uGroundAnchor;\n"
    "uniform float uGroundSpan;\n"
    "out vec4 FragColor;\n"
    "void main() {\n"
    "    vec3 N = normalize(vNorm);\n"
    "    float diff = max(dot(N, uSunDir), 0.0);\n"
    "    float amb = 0.42 + 0.18 * N.y;\n"
    "    float dayK = clamp(uSunDir.y * 1.4 + 0.45, 0.18, 1.05);\n"
    "    vec3 lum = vec3(0.25,0.55,0.20);\n"
    "    float exposure = uCliffMaterial!=0 ? 0.0 : 1.0-smoothstep(0.25,0.71,N.y);\n"
    "    float rockTone = mix(0.40,dot(vCol,lum),0.40);\n"
    "    vec3 stone = rockTone*vec3(1.06,1.02,0.97);\n"
    "    vec3 baseColor = mix(vCol,stone,exposure);\n"
    "    vec3 col = baseColor * (amb + diff * 0.72) * dayK * uLightScale * uTint;\n"
    "    col += baseColor * 0.035;\n"
    "    float dist = length(vPos - uCamPos);\n"
    "    /* 地面材质：世界坐标平铺，图案钉在世界里，走动不滚动 */\n"
    "    if (uGroundDetail > 0.01) {\n"
    "        vec2 uv = (vPos.xz + uGroundAnchor) / uGroundSpan;\n"
    "        vec3 g0 = texture(uGroundTex0, uv).rgb;\n"
    "        vec3 g1 = texture(uGroundTex1, uv).rgb;\n"
    "        vec3 ground = mix(g0, g1, uGroundMix);\n"
    "        if(uCliffMaterial!=0) ground=baseColor*(0.48+1.12*dot(ground,lum));\n"
    "        vec3 axis = abs(N);\n"
    "        vec3 blend = axis * axis;\n"
    "        blend *= blend;\n"
    "        blend /= blend.x + blend.y + blend.z;\n"
    "        vec3 sideUV = vec3(uv.x, vPos.y / uGroundSpan, uv.y) * 4.0;\n"
    "        vec3 du = dFdx(sideUV), dv = dFdy(sideUV);\n"
    "        if (blend.y < 0.98) {\n"
    "            vec3 gx = textureGrad(uGroundTex0, sideUV.zy, du.zy, dv.zy).rgb;\n"
    "            vec3 gz = textureGrad(uGroundTex0, sideUV.xy, du.xy, dv.xy).rgb;\n"
    "            float side = (dot(gx,lum)*blend.x + dot(gz,lum)*blend.z) / (1.0-blend.y);\n"
    "            vec3 sideColor = mix(baseColor,stone,0.40) * (0.48 + 1.12*side);\n"
    "            ground = mix(sideColor,ground,blend.y);\n"
    "        }\n"
    "        ground *= (amb + diff * 0.72) * dayK * uLightScale * uTint;\n"
    "        float fade = 1.0 - smoothstep(150.0, 520.0, dist);\n"
    "        col = mix(col, ground, 0.72 * fade * uGroundDetail);\n"
    "    }\n"
    "    if (uBrushRad > 0.5) {\n"
    "        float bd = length(vPos.xz - uBrushPos.xz);\n"
    "        if (abs(bd - uBrushRad) < 1.2) col = mix(col, vec3(0.95, 0.78, 0.25), 0.85);\n"
    "    }\n"
    "    float fog = uUnderwater != 0 ? clamp((dist - 1.0) / 35.0, 0.0, 1.0)\n"
    "              : clamp((dist - uFogRange.x) / max(uFogRange.y - uFogRange.x, 1e-3), 0.0, 1.0);\n"
    "    col = mix(col, uFogCol, clamp(fog, 0.0, 1.0));\n"
    "    FragColor = vec4(col, 1.0);\n"
    "}\n";

