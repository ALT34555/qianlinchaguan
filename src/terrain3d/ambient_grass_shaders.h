#ifndef QLCG_AMBIENT_GRASS_SHADERS_H
#define QLCG_AMBIENT_GRASS_SHADERS_H
#include "equipment_shaders.h"

static const char *GRASS_VS =
    "#version 330 core\n"
    "layout(location=0) in vec3 aPos;\n"
    "layout(location=1) in vec3 aBlade;\n"
    "layout(location=2) in vec3 iPos;\n"
    "layout(location=3) in vec2 iRotScale;\n"
    "layout(location=4) in vec4 iRoot;\n"
    "layout(location=5) in vec4 iTip;\n"
    "layout(location=6) in vec4 iNorm;\n"
    "layout(location=7) in float iSeason;\n"
    "layout(location=8) in vec4 iWater;\n"
    "uniform int       uLocalSeason;\n"
    "uniform vec4      uSeasonShape[4];\n"
    "uniform vec2      uFadeRange;\n"
    "uniform mat4      uMVP;\n"
    "uniform vec3      uCamPos;\n"
    "uniform float     uTime;\n"
    "uniform vec2      uWind;\n"
    "uniform float     uWaterMotion;\n"
    "uniform vec4      uGrassShape;\n"
    "uniform float     uRankSpan;\n"
    "uniform float     uStraw;\n"
    "uniform sampler2D uGroundTex0;\n"
    "uniform sampler2D uGroundTex1;\n"
    "uniform float     uGroundMix;\n"
    "uniform float     uGroundDetail;\n"
    "uniform vec2      uGroundAnchor;\n"
    "uniform float     uGroundSpan;\n"
    "out vec3  vPos;\n"
    "out vec3  vRootCol;\n"
    "out vec3  vTipCol;\n"
    "out vec3  vTerrNorm;\n"
    "out vec3  vBladeNorm;\n"
    "out float vH;\n"
    "out float vFrost;\n"
    "flat out float vAquatic;\n"
    "void main(){\n"
    "  vec4 shape = uGrassShape;\n"
    "  float straw = uStraw;\n"
    "  float fade = 1.0;\n"
    "  if (uLocalSeason != 0) {\n"
    "    int prev = (int(floor(iSeason)) + 4) % 4;\n"
    "    int next = (prev + 1) % 4;\n"
    "    float t = smoothstep(0.0, 1.0, fract(iSeason));\n"
    "    shape = mix(uSeasonShape[prev], uSeasonShape[next], t);\n"
    "    straw = uStraw * mix(prev == 3 ? 1.0 : 0.0, next == 3 ? 1.0 : 0.0, t);\n"
    "    fade = 1.0 - smoothstep(uFadeRange.x, uFadeRange.y, length(iPos.xz - uCamPos.xz));\n"
    "  }\n"
    "  vAquatic = iWater.x;\n"
    "  if (vAquatic > 0.5) {\n"
    "    shape.x = iWater.w;\n"
    "    shape.y = mix(0.90, 1.0, shape.y);\n"
    "    shape.z *= 0.77;\n"
    "    shape.w *= 1.15;\n"
    "    straw *= 0.20;\n"
    "  }\n"
    "  float growth = iNorm.a == 0.0 ? 1.0 : smoothstep(0.0, 1.0 - uRankSpan, shape.x - iNorm.a * uRankSpan);\n"
    "  if (growth * fade <= 0.0) { gl_Position = vec4(2.0, 2.0, 2.0, 1.0); return; }\n"
    "  float c = cos(iRotScale.x), s = sin(iRotScale.x);\n"
    "  float size = iRotScale.y * growth * fade;\n"
    "  float height = size * shape.y;\n"
    "  vec2 side = aBlade.xy * dot(aPos.xz, aBlade.xy);\n"
    "  vec2 bend = aPos.xz - side;\n"
    "  float spread = vAquatic > 0.5 ? min(size, 2.5) + 0.18 * max(0.0, size - 2.5) : size;\n"
    "  vec2 p = (side * shape.z + bend * shape.w) * spread;\n"
    "  float h = aBlade.z;\n"
    "  if (vAquatic > 0.5) p += vec2(0.13, -0.052) * h * h * spread;\n"
    "  float phase = iPos.x * 0.17 + iPos.z * 0.11;\n"
    "  float crown = sin(uTime * 1.35 + phase);\n"
    "  float breeze = sin(uTime * 2.15 + phase * 1.6 + iRotScale.x + aPos.x * 1.8 + aPos.z * 1.8);\n"
    "  float sway = (uWind.x * crown + uWind.y * breeze) * h * h * height;\n"
    "  vec2 wdir = vec2(0.92, 0.38) * sway;\n"
    "  if (vAquatic > 0.5) {\n"
    "    float wave = sin(uTime * 1.1 + phase + iRotScale.x);\n"
    "    vec2 drift = vec2(wave, sin(uTime * 0.91 - phase));\n"
    "    wdir = (iWater.yz * (0.30 + 0.10 * wave) + drift * 0.075) * h * h * min(height, 3.5) * uWaterMotion;\n"
    "  }\n"
    "  vec3 world = vec3(p.x * c - p.y * s, aPos.y * height, p.x * s + p.y * c) + iPos;\n"
    "  world.xz += wdir;\n"
    "  world.y -= dot(wdir, wdir) / max(1.72 * height, 0.25);\n"
    "  vec2 uv = (iPos.xz + uGroundAnchor) / max(uGroundSpan, 1.0);\n"
    "  float dist = length(iPos - uCamPos);\n"
    "  float lod = clamp(log2(max(dist * 0.08, 1.0)), 1.0, 5.0);\n"
    "  vec3 gtex = mix(textureLod(uGroundTex0, uv, lod).rgb,\n"
    "                  textureLod(uGroundTex1, uv, lod).rgb, uGroundMix);\n"
    "  vec3 lumW = vec3(0.25, 0.55, 0.20);\n"
    "  float snowV = smoothstep(0.70, 0.88, min(iRoot.r, min(iRoot.g, iRoot.b)));\n"
    "  gtex = mix(gtex, iRoot.rgb * (0.86 + 0.22 * dot(gtex, lumW)), snowV);\n"
    "  float gFade = 1.0 - smoothstep(150.0, 520.0, dist);\n"
    "  vRootCol = mix(iRoot.rgb, gtex, 0.72 * gFade * uGroundDetail * (1.0 - iRoot.a));\n"
    "  vTipCol = mix(iTip.rgb, vec3(0.43, 0.32, 0.20), straw);\n"
    "  vFrost = iTip.a * (1.0 - 0.6 * straw);\n"
    "  vTerrNorm = normalize(iNorm.xyz * 2.0 - 1.0);\n"
    "  vBladeNorm = normalize(vec3(aBlade.x * c - aBlade.y * s, 0.35, aBlade.x * s + aBlade.y * c));\n"
    "  vH = h;\n"
    "  vPos = world;\n"
    "  gl_Position = uMVP * vec4(world - uCamPos, 1.0);\n"
    "}\n";

static const char *GRASS_FS =
    "#version 330 core\n"
    "in vec3  vPos;\n"
    "in vec3  vRootCol;\n"
    "in vec3  vTipCol;\n"
    "in vec3  vTerrNorm;\n"
    "in vec3  vBladeNorm;\n"
    "in float vH;\n"
    "in float vFrost;\n"
    "flat in float vAquatic;\n"
    "uniform vec3  uSunDir;\n"
    "uniform vec3  uCamPos;\n"
    "uniform vec3  uFogCol;\n"
    "uniform vec2  uFogRange;\n"
    QLCG_EQUIPMENT_VISION
    "uniform int   uUnderwater;\n"
    "uniform float uLightScale;\n"
    "uniform vec3  uTint;\n"
    "uniform int   uEnhanced;\n"
    "uniform vec3  uSunColor;\n"
    "uniform vec3  uSkyAmb;\n"
    "uniform vec3  uGroundAmb;\n"
    "uniform float uWet;\n"
    "uniform float uSnowAmt;\n"
    "uniform float uTipSnow;\n"
    "uniform mat4  uShadowVP;\n"
    "uniform highp sampler2DShadow uShadowTex;\n"
    "uniform int   uShadowOn;\n"
    "uniform vec2  uShadowTexel;\n"
    "out vec4 frag;\n"
    "vec3 qlcgHighlight(vec3 color){\n"
    "  float peak = max(color.r, max(color.g, color.b));\n"
    "  float high = max(peak - 0.75, 0.0);\n"
    "  return color * ((0.75 + 0.25 * high / (0.25 + high)) / max(peak, 0.75));\n"
    "}\n"
    "float qlcgShadow(vec3 wp){\n"
    "  if (uShadowOn == 0) return 1.0;\n"
    "  vec4 sc = uShadowVP * vec4(wp, 1.0);\n"
    "  vec3 pc = sc.xyz / sc.w * 0.5 + 0.5;\n"
    "  if (pc.x <= 0.0 || pc.x >= 1.0 || pc.y <= 0.0 || pc.y >= 1.0 || pc.z >= 1.0) return 1.0;\n"
    "  float sum = 0.0;\n"
    "  for (int i = -1; i <= 1; i++)\n"
    "    for (int j = -1; j <= 1; j++)\n"
    "      sum += texture(uShadowTex, vec3(pc.xy + vec2(float(i), float(j)) * uShadowTexel, pc.z - 0.0012));\n"
    "  return mix(sum / 9.0, 1.0, smoothstep(0.84, 1.0, max(abs(pc.x * 2.0 - 1.0), abs(pc.y * 2.0 - 1.0))));\n"
    "}\n"
    "void main(){\n"
    "  float h = clamp(vH, 0.0, 1.0);\n"
    "  float tipMix = smoothstep(0.06, mix(0.78, 0.52, vAquatic), h);\n"
    "  vec3 albedo = mix(vRootCol, vTipCol, tipMix);\n"
    "  vec3 N = normalize(vTerrNorm);\n"
    "  vec3 BN = normalize(vBladeNorm);\n"
    "  float diff = max(dot(N, uSunDir), 0.0);\n"
    "  float bladeFace = clamp(abs(dot(BN, uSunDir)) * 0.65 + 0.35, 0.0, 1.0);\n"
    "  float bladeShade = mix(1.0, 0.90 + 0.20 * bladeFace, tipMix * 0.75);\n"
    "  vec3 c;\n"
    "  if (uEnhanced != 0) {\n"
    "    float vis = qlcgShadow(vPos);\n"
    "    vec3 ambi = mix(uGroundAmb, uSkyAmb, clamp(N.y * 0.5 + 0.5, 0.0, 1.0));\n"
    "    vec3 lit = (ambi + uSunColor * (diff * 1.05 * vis)) * uLightScale * uTint;\n"
    "    c = albedo * lit * bladeShade * mix(1.0, 1.0 - 0.16 * uWet, tipMix);\n"
    "    float rootSnow = smoothstep(0.40, 0.86, N.y) * uSnowAmt * 0.92 * 0.28 * (1.0 - tipMix);\n"
    "    float tipSnow = max(uTipSnow, vFrost * 0.35) * tipMix;\n"
    "    float snowW = clamp(max(rootSnow, tipSnow), 0.0, 0.65) * (1.0 - vAquatic);\n"
    "    if (snowW > 0.005) {\n"
    "      vec3 snowCol = vec3(0.90, 0.94, 1.00) * (ambi * 0.85 + uSunColor * 0.75 * vis) * uLightScale;\n"
    "      c = mix(c, snowCol, snowW);\n"
    "    }\n"
    "    c = qlcgHighlight(c);\n"
    "  } else {\n"
    "    float amb = 0.42 + 0.18 * N.y;\n"
    "    float dayK = clamp(uSunDir.y * 1.4 + 0.45, 0.18, 1.05);\n"
    "    vec3 lit = (amb + diff * 0.72) * dayK * uLightScale * uTint;\n"
    "    c = albedo * lit * bladeShade + albedo * 0.010;\n"
    "    float snowW = clamp(uTipSnow * tipMix, 0.0, 0.65) * (1.0 - vAquatic);\n"
    "    if (snowW > 0.005) {\n"
    "      vec3 snowCol = vec3(0.90, 0.94, 1.00) * (amb + diff * 0.72) * dayK * uLightScale;\n"
    "      c = mix(c, snowCol, snowW);\n"
    "    }\n"
    "  }\n"
    "  float dist = length(vPos - uCamPos);\n"
    "  float fog = uUnderwater != 0 ? qlcgWaterFog(dist)\n"
    "            : clamp((dist - uFogRange.x) / max(uFogRange.y - uFogRange.x, 1e-3), 0.0, 1.0);\n"
    "  c = qlcgEquipmentLight(c, vPos - uCamPos, dist);\n"
    "  c = mix(c, uFogCol, clamp(fog, 0.0, 1.0));\n"
    "  frag = vec4(c, 1.0);\n"
    "}\n";

#endif
